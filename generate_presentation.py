"""
Генератор презентации проекта «Портал достижений лицея» для защиты на хакатоне.
Создаёт современную презентацию в формате 16:9 в едином стиле сайта:
тёмно-синий градиент, сапфировые акценты, карточки, строгая типографика.
"""

import os
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from pptx.enum.shapes import MSO_SHAPE

def create_deck():
    prs = Presentation()
    # Формат 16:9
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    # Цветовая палитра сайта
    BG_COLOR = RGBColor(11, 19, 43)        # #0b132b
    CARD_BG = RGBColor(23, 37, 84)         # #172554
    ACCENT_CYAN = RGBColor(56, 189, 248)   # #38bdf8
    ACCENT_BLUE = RGBColor(96, 165, 250)   # #60a5fa
    TEXT_WHITE = RGBColor(248, 250, 252)   # #f8fafc
    TEXT_MUTED = RGBColor(148, 163, 184)   # #94a3b8
    GREEN_COLOR = RGBColor(52, 211, 153)   # #34d399
    AMBER_COLOR = RGBColor(251, 191, 36)   # #fbbf24

    blank_layout = prs.slide_layouts[6]

    def set_slide_background(slide):
        bg = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, prs.slide_height)
        bg.fill.solid()
        bg.fill.fore_color.rgb = BG_COLOR
        bg.line.fill.background() # Без контура
        return bg

    def add_header(slide, tag_text, title_text):
        # Бейдж-тег
        tag_box = slide.shapes.add_textbox(Inches(0.8), Inches(0.5), Inches(8), Inches(0.4))
        tf = tag_box.text_frame
        tf.word_wrap = True
        p = tf.paragraphs[0]
        p.text = tag_text.upper()
        p.font.size = Pt(11)
        p.font.bold = True
        p.font.color.rgb = ACCENT_CYAN

        # Заголовок
        title_box = slide.shapes.add_textbox(Inches(0.8), Inches(0.85), Inches(11), Inches(0.8))
        tf2 = title_box.text_frame
        tf2.word_wrap = True
        p2 = tf2.paragraphs[0]
        p2.text = title_text
        p2.font.size = Pt(24)
        p2.font.bold = True
        p2.font.color.rgb = TEXT_WHITE

    def add_card(slide, left, top, width, height, title, items, border_color=None):
        card = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, left, top, width, height)
        card.fill.solid()
        card.fill.fore_color.rgb = CARD_BG
        if border_color:
            card.line.color.rgb = border_color
            card.line.width = Pt(1.5)
        else:
            card.line.color.rgb = RGBColor(30, 41, 59)
            card.line.width = Pt(1)

        tb = slide.shapes.add_textbox(left + Inches(0.2), top + Inches(0.15), width - Inches(0.4), height - Inches(0.3))
        tf = tb.text_frame
        tf.word_wrap = True

        if title:
            p = tf.paragraphs[0]
            p.text = title
            p.font.size = Pt(15)
            p.font.bold = True
            p.font.color.rgb = TEXT_WHITE
            p.space_after = Pt(8)

        for item in items:
            p = tf.add_paragraph()
            p.text = item
            p.font.size = Pt(12)
            p.font.color.rgb = TEXT_MUTED
            p.space_after = Pt(6)

    # =========================================================================
    # СЛАЙД 1: Титульный
    # =========================================================================
    s1 = prs.slides.add_slide(blank_layout)
    set_slide_background(s1)

    # Декоративный бейдж
    badge = s1.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(0.8), Inches(1.5), Inches(3.2), Inches(0.45))
    badge.fill.solid()
    badge.fill.fore_color.rgb = RGBColor(15, 23, 42)
    badge.line.color.rgb = ACCENT_CYAN
    btf = badge.text_frame
    bp = btf.paragraphs[0]
    bp.alignment = PP_ALIGN.CENTER
    bp.text = "ХАКАТОН • 9–11 КЛАССЫ"
    bp.font.size = Pt(12)
    bp.font.bold = True
    bp.font.color.rgb = ACCENT_CYAN

    # Главный заголовок
    tb1 = s1.shapes.add_textbox(Inches(0.8), Inches(2.2), Inches(11.5), Inches(1.8))
    tf1 = tb1.text_frame
    tf1.word_wrap = True
    p = tf1.paragraphs[0]
    p.text = "ПОРТАЛ ДОСТИЖЕНИЙ ЛИЦЕЯ"
    p.font.size = Pt(40)
    p.font.bold = True
    p.font.color.rgb = TEXT_WHITE

    p_sub = tf1.add_paragraph()
    p_sub.text = "Учёт успехов по физике, математике и информатике: верификация, портфолио, рейтинг и Telegram-бот"
    p_sub.font.size = Pt(16)
    p_sub.font.color.rgb = ACCENT_CYAN
    p_sub.space_before = Pt(8)

    # Карточка команды
    add_card(s1, Inches(0.8), Inches(4.3), Inches(11.7), Inches(2.2), "Команда разработчиков (9Б класс)", [
        "Гумеров Раиль — капитан, Full-stack разработка, архитектура API и верификации",
        "Фаррахов Ислам — интеграция с Telegram Bot API, разработка HobbitBot",
        "Якубов Амир — проектирование схемы базы данных (PostgreSQL / SQLite) и аудит коллизий",
        "Биктагиров Самир, Авдошин Радислав, Яруллин Самат — UX/UI дизайн, алгоритмы рейтинга и тестирование"
    ], border_color=ACCENT_CYAN)

    # =========================================================================
    # СЛАЙД 2: Проблема и Решение
    # =========================================================================
    s2 = prs.slides.add_slide(blank_layout)
    set_slide_background(s2)
    add_header(s2, "Проблематика & Ценность продукта", "Зачем лицею единый цифровой портал достижений?")

    add_card(s2, Inches(0.8), Inches(1.8), Inches(5.6), Inches(5.0), "❌ Как устроено сейчас (Проблемы)", [
        "• Бумажный хаос грамот: дипломы олимпиад и хакатонов оседают дома в папках и теряются к 11 классу.",
        "• Непрозрачный отбор: при распределении в профильные классы и начислении стипендий сложно учесть все успехи объективно.",
        "• Перегрузка учителей: ручной сбор подтверждений и сведение отчётов в Excel отнимают десятки часов.",
        "• Отсутствие единого профиля: ученик не видит свой реальный рейтинг и отставание от стипендии."
    ], border_color=RGBColor(239, 68, 68))

    add_card(s2, Inches(6.8), Inches(1.8), Inches(5.7), Inches(5.0), "✅ Наше цифровое решение", [
        "• Единый личный кабинет: ученик загружает достижения, сканы дипломов и видит свой прогресс.",
        "• Прозрачная верификация: учитель проверяет скан диплома и подтверждает/отклоняет заявку в 1 клик.",
        "• Автоматический пересчёт: баллы начисляются по утверждённой матрице (тип + уровень + результат).",
        "• Мобильный доступ: Telegram-бот HobbitBot для быстрой подачи заявок со смартфона.",
        "• Готовое портфолио: мгновенная генерация официального PDF-документа для вузов и комиссий."
    ], border_color=GREEN_COLOR)

    # =========================================================================
    # СЛАЙД 3: Система баллов и прозрачность
    # =========================================================================
    s3 = prs.slides.add_slide(blank_layout)
    set_slide_background(s3)
    add_header(s3, "Система оценивания & Мотивация", "Справедливая матрица начисления баллов")

    add_card(s3, Inches(0.8), Inches(1.8), Inches(3.7), Inches(5.0), "🎯 Предметный фокус", [
        "Ключевые дисциплины лицея:",
        "• ⚛️ Физика (ВсОШ, Росатом, олимпиада «Шаг в будущее»)",
        "• 📐 Математика (городские матбои, турнир Ломоносова)",
        "• 💻 Информатика (хакатоны, олимпиады по IT, робототехника)",
        "• 🚀 Научные проекты и конференции",
        "• 🤝 Волонтёрство и социальные часы"
    ])

    add_card(s3, Inches(4.8), Inches(1.8), Inches(3.7), Inches(5.0), "📊 Градация уровней", [
        "Баллы зависят от масштаба:",
        "• Федеральный / Всерос: до 70 баллов",
        "• Региональный: до 50 баллов",
        "• Городской: до 35 баллов",
        "• Школьный этап: до 20 баллов",
        "",
        "Градация результатов:",
        "Победитель > Призёр > Участник"
    ], border_color=ACCENT_CYAN)

    add_card(s3, Inches(8.8), Inches(1.8), Inches(3.7), Inches(5.0), "🛡 Защита от накрутки", [
        "Почему система надёжна?",
        "1. Ученик не вводит баллы вручную — их вычисляет алгоритм по матрице правил.",
        "2. Баллы начисляются в рейтинг ТОЛЬКО после проверки учителем.",
        "3. Обязательное прикрепление ссылки на подтверждающий диплом/скан.",
        "4. При отклонении учитель обязан указать причину."
    ], border_color=GREEN_COLOR)

    # =========================================================================
    # СЛАЙД 4: Архитектура и База данных (9-11 классы)
    # =========================================================================
    s4 = prs.slides.add_slide(blank_layout)
    set_slide_background(s4)
    add_header(s4, "Техническая архитектура (9–11 классы)", "Инженерия данных, безопасность и краевые случаи")

    add_card(s4, Inches(0.8), Inches(1.8), Inches(5.6), Inches(5.0), "🏛 3-звенная архитектура", [
        "• UI (Интерфейс): адаптивный HTML5 / CSS3 / ES6, работает без установки серверов прямо из архива.",
        "• API-Слой (api.js): изолированная бизнес-логика. Методы готовы к замене на fetch() к бэкенду без правки интерфейса.",
        "• Схема БД (schema.sql): PostgreSQL в 3-й нормальной форме. Включает таблицы users, achievements, points_matrix, аудит.",
        "• Локальный бэкенд: скрипт database/init_sqlite.py для развёртывания базы на SQLite."
    ])

    add_card(s4, Inches(6.8), Inches(1.8), Inches(5.7), Inches(5.0), "⚡ Решение краевых случаев", [
        "• Коллизия: 2 администратора подтверждают одно достижение:",
        "  Реализована оптимистичная блокировка. Статус меняется строго из 'pending'. Повторное подтверждение отклоняется ошибкой с фиксацией первого админа.",
        "",
        "• Чужой диплом или фальсификация:",
        "  Проверка скана диплома по реестру/протоколу, отклонение с публичным комментарием.",
        "",
        "• Безопасность:",
        "  Хеширование паролей, санитизация через esc() против XSS, параметризованные SQL-запросы."
    ], border_color=ACCENT_CYAN)

    # =========================================================================
    # СЛАЙД 5: Telegram-бот HobbitBot
    # =========================================================================
    s5 = prs.slides.add_slide(blank_layout)
    set_slide_background(s5)
    add_header(s5, "Мобильная интеграция", "Telegram-бот лицея HobbitBot")

    add_card(s5, Inches(0.8), Inches(1.8), Inches(5.6), Inches(5.0), "🤖 Возможности бота", [
        "• Авторизация ученика: /login <логин> <пароль> с привязкой сессии.",
        "• 📊 Мой рейтинг: мгновенный просмотр текущих баллов с детализацией по физике, математике и IT.",
        "• 🏆 Топ-10 лицея: просмотр лидеров рейтинга в реальном времени.",
        "• ➕ Подача достижения: пошаговый мастер прямо в чате со смартфона (название → категория → результат).",
        "• 📜 Статус заявок: мониторинг статуса проверки учителем.",
        "• 🤖 Совет ИИ: персональная подсказка, где добрать баллы."
    ], border_color=ACCENT_CYAN)

    add_card(s5, Inches(6.8), Inches(1.8), Inches(5.7), Inches(5.0), "💡 Реализация и демонстрация", [
        "Два дополняющих решения команды:",
        "",
        "1. Серверный бот на чистом Python (bot/telegram_bot.py):",
        "• Работает без внешних зависимостей (только urllib и json).",
        "• Быстрый запуск в 1 клик через run_bot.bat.",
        "• Подключён реальный бот HobbitBot.",
        "",
        "2. Интерактивный веб-симулятор (bot.html):",
        "• Точная копия интерфейса Telegram в браузере.",
        "• Позволяет жюри протестировать сценарии бота офлайн без интернета!",
        "• Полная синхронизация с базой данных портала."
    ])

    # =========================================================================
    # СЛАЙД 6: Личный кабинет ученика и Портфолио
    # =========================================================================
    s6 = prs.slides.add_slide(blank_layout)
    set_slide_background(s6)
    add_header(s6, "UX/UI & Инновации", "Личный кабинет, PDF-портфолио и ИИ-помощник")

    add_card(s6, Inches(0.8), Inches(1.8), Inches(3.7), Inches(5.0), "📄 Официальное портфолио", [
        "• Генерация чистого документа для приёмных комиссий и стипендиальных советов.",
        "• Автоматическая сводка по категориям STEM.",
        "• Список подтверждённых достижений с датами и баллами.",
        "• Экспорт в PDF / печать в 1 клик (Ctrl+P)."
    ])

    add_card(s6, Inches(4.8), Inches(1.8), Inches(3.7), Inches(5.0), "🤖 ИИ-помощник лицеиста", [
        "• Анализирует баланс дисциплин (STEM-аудит).",
        "• Рассчитывает отставание от порога академической стипендии (60+ баллов).",
        "• Выявляет пробелы (например, 'нет достижений по математике').",
        "• Рекомендует конкретные турниры для участия."
    ], border_color=ACCENT_CYAN)

    add_card(s6, Inches(8.8), Inches(1.8), Inches(3.7), Inches(5.0), "🎖 Элементы геймификации", [
        "• 4 ступени прогресса: Новичок → Активист → Мастер наук → Легенда лицея.",
        "• Тематические бейджи:",
        "  ⚛️ «Юный Ньютон» (физика)",
        "  📐 «Архимед» (математика)",
        "  💻 «Кодер лицея» (IT)",
        "  🏆 «Чемпион» (2+ победы)."
    ], border_color=GREEN_COLOR)

    # =========================================================================
    # СЛАЙД 7: Админ-панель и Рейтинговая система
    # =========================================================================
    s7 = prs.slides.add_slide(blank_layout)
    set_slide_background(s7)
    add_header(s7, "Инструменты администратора & Рейтинг", "Управление качеством данных и соревновательный дух")

    add_card(s7, Inches(0.8), Inches(1.8), Inches(5.6), Inches(5.0), "⚙️ Кабинет учителя / администратора", [
        "• Экспресс-панель модерации: проверка входящих заявок учеников.",
        "• Просмотр прикреплённых сканов дипломов по ссылке.",
        "• Быстрые действия: '✓ Принять' / '✗ Отклонить' с обязательной фиксацией причины.",
        "• Прямое внесение достижений любому ученику от имени лицея.",
        "• Экспорт отчёта в CSV (с поддержкой Excel UTF-8 BOM) для школьной отчётности."
    ])

    add_card(s7, Inches(6.8), Inches(1.8), Inches(5.7), Inches(5.0), "🏆 Рейтинговая система (Лидерборд)", [
        "• Подиум лидеров: Топ-10 учеников с золотым, серебряным и бронзовым оформлением.",
        "• Гибкие фильтры:",
        "  - По направлениям (Физика / Математика / Информатика)",
        "  - По классам (9А, 9Б, 10А, 11Б)",
        "  - По периодам дат (четверть, полугодие, учебный год).",
        "• Подсветка строки текущего ученика в общей таблице лицея."
    ], border_color=ACCENT_CYAN)

    # =========================================================================
    # СЛАЙД 8: Перспективы и Демонстрация
    # =========================================================================
    s8 = prs.slides.add_slide(blank_layout)
    set_slide_background(s8)
    add_header(s8, "План масштабирования & Защита", "Готовность к внедрению и перспективы развития")

    add_card(s8, Inches(0.8), Inches(1.8), Inches(5.6), Inches(5.0), "🚀 План масштабирования (Roadmap)", [
        "1. Интеграция с электронным журналом (ЭЖД):",
        "   Автоматическая синхронизация списков учеников и классов.",
        "",
        "2. Серверное хранилище дипломов (S3 / WebDAV):",
        "   Прямая загрузка PDF-файлов и изображений с автоматическим OCR-распознаванием печатей.",
        "",
        "3. Интеграция с Госуслугами / РДДМ:",
        "   Верификация лицейских портфолио для получения доп. баллов к ЕГЭ."
    ])

    add_card(s8, Inches(6.8), Inches(1.8), Inches(5.7), Inches(5.0), "✨ Итоги проекта", [
        "• 100% готовность прототипа: веб-платформа открывается локально двойным кликом.",
        "• Telegram-бот HobbitBot настроен и работает с реальным Bot API.",
        "• Полное соответствие всем критериям группы 9–11 классов.",
        "",
        "Готовы перейти к живой демонстрации прототипа!",
        "Спасибо за внимание!"
    ], border_color=GREEN_COLOR)

    # Сохранение презентации
    out_dir = os.path.join(os.path.dirname(__file__), "presentation")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "Портал_достижений_лицея_9-11_класс.pptx")
    prs.save(out_path)
    print(f"Презентация успешно создана: {out_path}")

if __name__ == "__main__":
    create_deck()
